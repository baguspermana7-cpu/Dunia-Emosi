#!/usr/bin/env python3
"""PRD-59 L23: write games/uae/uae-i18n-en.js from the translation tables in games/uae/i18n/*.json.

Each table is {"teks Indonesia": "English text"}. The pattern rules for sentences built around numbers and names live
in games/uae/i18n/rules.js and are appended verbatim. Run after editing a table: python3 tools/build-uae-i18n.py
(--check exits 1 when the generated file is stale)."""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'games', 'uae', 'i18n')
OUT = os.path.join(ROOT, 'games', 'uae', 'uae-i18n-en.js')


def build() -> str:
    merged: dict[str, str] = {}
    for path in sorted(glob.glob(os.path.join(SRC, '*.json'))):
        for key, value in json.load(open(path, encoding='utf-8')).items():
            key = ' '.join(key.split())
            if key in merged and merged[key] != value:
                raise SystemExit('two English texts for one Indonesian text: %r (%s)' % (key, os.path.basename(path)))
            merged[key] = value   # same text in both languages is kept: a joined text needs every part
    rules = open(os.path.join(SRC, 'rules.js'), encoding='utf-8').read().strip()
    lines = ['/* GENERATED by tools/build-uae-i18n.py from games/uae/i18n/. Do not edit by hand. */',
             '(function (root) {', "  'use strict'", '  var map = {']
    lines += ['    %s: %s,' % (json.dumps(k, ensure_ascii=False), json.dumps(merged[k], ensure_ascii=False)) for k in sorted(merged)]
    lines += ['  }', '  ' + rules.replace('\n', '\n  '), '  var out = { map: map, rules: rules }',
              "  if (typeof module !== 'undefined' && module.exports) module.exports = out",
              '  root.UAEI18N_EN = out', "})(typeof window !== 'undefined' ? window : globalThis)", '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        stale = not os.path.exists(OUT) or open(OUT, encoding='utf-8').read() != text
        sys.stdout.write('uae-i18n-en.js is %s\n' % ('STALE: run tools/build-uae-i18n.py' if stale else 'fresh'))
        sys.exit(1 if stale else 0)
    open(OUT, 'w', encoding='utf-8').write(text)
    sys.stdout.write('wrote %s (%d bytes)\n' % (os.path.relpath(OUT, ROOT), len(text.encode())))
