await p.goto('http://localhost:8081/games/timmy-kapal.html', { waitUntil: 'networkidle2' })
await p.evaluate(() => { __tk.reset(); __tk.unlockAll() }); await sleep(500)
await p.evaluate(() => __tk.start('titanic', 3)); await sleep(1500)
