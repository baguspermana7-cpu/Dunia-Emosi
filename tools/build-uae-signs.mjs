#!/usr/bin/env node
// PRD-59B §8: import downloaded UAE sign images (staging dir with CREDITS.json from the Wikipedia gallery
// "Road signs in the United Arab Emirates") into games/uae/signs/ and write games/uae/uae-signs-credits.js.
// Images are Wikimedia's own 500 px PNG thumbnails of each SVG (originals are rate-limited for scripts), stored as
// WebP. Refuses any file that is not a WebP and any
// licence that is not free (public domain, CC0, CC BY, CC BY-SA). Only codes listed in uae-signs-real.js are taken.
// Usage: node tools/build-uae-signs.mjs <staging-dir>
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const R = require('../games/uae/uae-signs-real.js')
const dir = process.argv[2]
if (!dir || !fs.existsSync(path.join(dir, 'CREDITS.json'))) { console.error('usage: node tools/build-uae-signs.mjs <staging-dir with CREDITS.json>'); process.exit(2) }
const OUT = 'games/uae/signs'
const FREE = /^(public domain|cc0|cc by(-sa)? \d\.\d)/i
const credits = JSON.parse(fs.readFileSync(path.join(dir, 'CREDITS.json'), 'utf8')).signs
fs.mkdirSync(OUT, { recursive: true })
const out = {}, refused = []
for (const c of credits) {
  if (!R.byCode[c.code]) continue
  const src = path.join(dir, c.code + '.webp')
  if (!fs.existsSync(src)) { refused.push(c.code + ': file missing'); continue }
  const img = fs.readFileSync(src)
  // a raster image cannot carry script; check it really is a WebP (RIFF....WEBP) and not an HTML error page
  if (img.length < 200 || img.toString('latin1', 0, 4) !== 'RIFF' || img.toString('latin1', 8, 12) !== 'WEBP') { refused.push(c.code + ': not a webp'); continue }
  if (!FREE.test(c.licence || '')) { refused.push(c.code + ': licence "' + c.licence + '"'); continue }
  if (!/^https:\/\//.test(c.page || '')) { refused.push(c.code + ': no https source page'); continue }
  fs.writeFileSync(path.join(OUT, c.code + '.webp'), img)
  out[c.code] = { file: c.file.replace(/^File:/, ''), licence: c.licence, artist: (c.artist || '').replace(/\s+/g, ' ').trim(), page: c.page, sha1: c.sha1, thumb: c.thumb || '' }
}
const js = `/* GENERATED by tools/build-uae-signs.mjs from the Wikimedia Commons metadata of each file. Do not edit by hand.
   Every file in games/uae/signs/ has an entry: Commons file name, licence, author, source page, sha1. */
(function (root) {
  'use strict'
  var C = ${JSON.stringify(out, null, 1)}
  root.UAESignCredits = C
  if (typeof module !== 'undefined' && module.exports) module.exports = C
})(typeof window !== 'undefined' ? window : globalThis)
`
fs.writeFileSync('games/uae/uae-signs-credits.js', js)
console.log(`imported ${Object.keys(out).length} of ${R.list.length} listed signs; refused ${refused.length}`)
refused.forEach(r => console.log('  refused ' + r))
const missing = R.list.filter(x => !out[x.code]).map(x => x.code)
if (missing.length) console.log('  not available yet: ' + missing.join(', '))
